function render160Points() {
    const container = document.getElementById('points-container');
    if (!container) return;

    let html = '';
    DOMAINS_DATA.forEach(domain => {
        html += `
            <div class="glass-card rounded-2xl p-6 space-y-4">
                <div class="flex items-center gap-3 border-b border-gold-500/20 pb-3">
                    <span class="text-2xl">${domain.icon}</span>
                    <h3 class="text-lg md:text-xl font-bold text-gold-400 font-cinzel">${domain.title}</h3>
                </div>
                <div class="grid grid-cols-1 md:grid-cols-2 gap-4">
        `;

        domain.points.forEach(p => {
            html += `
                <div class="point-card p-4 rounded-xl bg-cosmic-800/60 border border-slate-700/50 hover:border-gold-500/40 transition-all">
                    <div class="flex items-start gap-2">
                        <span class="w-6 h-6 rounded-full bg-gold-500/20 text-gold-400 text-xs font-bold flex items-center justify-center shrink-0 mt-0.5">${p.num}</span>
                        <div>
                            <h4 class="text-sm font-bold text-white">${p.title}</h4>
                            <span class="inline-block text-[11px] text-amber-300/80 bg-amber-500/10 px-2 py-0.5 rounded mt-1 font-hindi">सूत्र: ${p.rule}</span>
                            <p class="text-xs text-slate-300 mt-2 font-hindi leading-relaxed">${p.desc}</p>
                        </div>
                    </div>
                </div>
            `;
        });

        html += `
                </div>
            </div>
        `;
    });

    container.innerHTML = html;
}

function filter160Points() {
    const query = document.getElementById('search160').value.toLowerCase().trim();
    const cards = document.querySelectorAll('.point-card');
    cards.forEach(card => {
        const text = card.textContent.toLowerCase();
        if (text.includes(query)) {
            card.style.display = 'block';
        } else {
            card.style.display = 'none';
        }
    });
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', () => {
    render160Points();
});
